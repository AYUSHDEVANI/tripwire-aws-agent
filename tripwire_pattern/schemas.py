"""
Tripwire Pydantic Schemas
Defines core data models for the decision cascade, audit logging, and policy evaluation.
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
import time
import uuid


class DecisionCategory(str, Enum):
    ALLOW = "ALLOW"
    ASK = "ASK"
    ESCALATE = "ESCALATE"
    BLOCK = "BLOCK"


class DeciderLabel(str, Enum):
    GROUNDED = "grounded"
    UNGROUNDED = "ungrounded"
    UNSURE = "unsure"


class DeciderResult(BaseModel):
    """Result returned by Strands Decider 2B."""
    label: DeciderLabel = DeciderLabel.UNSURE
    confidence: float = Field(default=0.0, ge=0.0, le=1.0)
    latency_ms: float = 0.0
    model_id: str = "strands-decider-2b"
    raw_output: Optional[Dict[str, Any]] = None


class PolicyResult(BaseModel):
    """Deterministic security and authorization evaluation."""
    passed: bool = True
    violations: List[str] = Field(default_factory=list)
    requires_confirmation: bool = False
    is_destructive: bool = False
    caller_role: str = "operator"
    target_environment: str = "staging"


class TripwireDecision(BaseModel):
    """Normalized decision outcome generated by the Tripwire Decision Cascade."""
    decision_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    tool_name: str
    tool_args: Dict[str, Any] = Field(default_factory=dict)
    sanitized_args: Dict[str, Any] = Field(default_factory=dict)
    category: DecisionCategory
    confidence: Optional[float] = None
    decider_label: Optional[DeciderLabel] = None
    rationale: str
    evidence: List[str] = Field(default_factory=list)
    policy_passed: bool = True
    requires_confirmation: bool = False
    escalated: bool = False
    executed: bool = False
    latency_ms: float = 0.0
    clarification_prompt: Optional[str] = None
    pending_token: Optional[str] = None
    error: Optional[str] = None
    timestamp: float = Field(default_factory=time.time)


class AuditEvent(BaseModel):
    """Structured audit event logged to JSONL for SIEM and compliance."""
    timestamp: str
    decision_id: str
    user_message: str
    tool_name: str
    tool_args: Dict[str, Any]
    decider_label: Optional[str] = None
    confidence: Optional[float] = None
    lane: str
    final_action: str
    execution_result: Optional[Any] = None
    latency_ms: float = 0.0
    caller_role: str = "operator"
    metadata: Dict[str, Any] = Field(default_factory=dict)


class PendingAction(BaseModel):
    """Pending action awaiting human confirmation or clarification."""
    token: str = Field(default_factory=lambda: str(uuid.uuid4()))
    user_message: str
    tool_name: str
    tool_args: Dict[str, Any]
    question: str
    created_at: float = Field(default_factory=time.time)
    expires_at: float
    used: bool = False
